/// Supported languages, matching the Capacitor app's i18n provider.
enum AppLanguage { english, amharic, oromo }

extension AppLanguageX on AppLanguage {
  String get code => switch (this) {
        AppLanguage.english => 'en',
        AppLanguage.amharic => 'am',
        AppLanguage.oromo => 'om',
      };

  String get label => switch (this) {
        AppLanguage.english => 'English',
        AppLanguage.amharic => 'አማርኛ',
        AppLanguage.oromo => 'Afaan Oromoo',
      };

  static AppLanguage fromCode(String? code) => switch (code) {
        'am' => AppLanguage.amharic,
        'om' => AppLanguage.oromo,
        _ => AppLanguage.english,
      };
}

