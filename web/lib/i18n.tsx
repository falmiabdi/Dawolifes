interface I18nContextType {
  lang: Language
  setLang: (l: Language) => void
  t: (key: string) => string
  tv: (value: string) => string
}

const I18nContext = createContext<I18nContextType>({
  lang: "en",
  setLang: () => {},
  t: (key: string) => key,
  tv: (value: string) => value,
})

export function useI18n() {
  return useContext(I18nContext)
}

function readStoredLang(): Language {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    if (stored === "en" || stored === "am" || stored === "om") return stored
  } catch {}
  return "en"
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Language>("en")

  useEffect(() => {
    setLangState(readStoredLang())
  }, [])

  function setLang(l: Language) {
    setLangState(l)
    try {
      window.localStorage.setItem(STORAGE_KEY, l)
    } catch {}
  }

  function t(key: string) {
    return STRINGS[lang][key] || FORM_STRINGS[lang][key] || STRINGS.en[key] || FORM_STRINGS.en[key] || key
  }

  function tv(value: string) {
    if (!value) return value
    return VALUE_STRINGS[lang][value] || value
  }

  return (
    <I18nContext.Provider value={{ lang, setLang, t, tv }}>
      {children}
    </I18nContext.Provider>
  )
}
